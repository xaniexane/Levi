def _gen_test_models(plan: BuildPlan) -> str:
    cases = []
    for m in plan.data_model:
        cls = _class_name(m.name)
        cases.append(
            "\n".join(
                [
                    "    %s_instance = %s(name=\"valid\")" % (m.name, cls),
                    "    assert %s_instance.validate() == [], \"valid model must pass\"" % m.name,
                    "    bad = %s(name=\"   \")" % cls,
                    '    assert any("name" in e for e in bad.validate()), "blank name must fail"',
                    "    roundtrip = %s.from_dict(%s_instance.to_dict())" % (cls, m.name),
                    '    assert roundtrip.name == "valid", "dict roundtrip must preserve fields"',
                ]
            )
        )
    imports = ", ".join(_class_name(m.name) for m in plan.data_model)
    return "\n".join(
        [
            '"""Model tests: validation and serialization. stdlib only."""',
            "import os",
            "import sys",
            "",
            "sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))",
            "",
            "from api.models import %s  # noqa: E402" % imports,
            "",
            "",
            "def main() -> None:",
        ]
        + ["    " + line for block in cases for line in block.split("\n")]
        + [
            '        print("models OK: %s")' % ", ".join(m.name for m in plan.data_model),
            "",
            "",
            'if __name__ == "__main__":',
            "    main()",
            "",
        ]
    )


