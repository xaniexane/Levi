_PY_DEFAULTS = {"str": '""', "int": "0", "float": "0.0", "bool": "False"}


def _class_name(entity: str) -> str:
    return "".join(part.capitalize() for part in entity.split("_")) or "Item"


def _gen_models(plan: BuildPlan) -> str:
    """Entity dataclasses with validation. Models decide truth."""
    classes = []
    for entity_model in plan.data_model:
        cls = _class_name(entity_model.name)
        field_lines = []
        check_lines = []
        for f in entity_model.fields:
            if f.name == "id":
                continue
            default = _PY_DEFAULTS.get(f.type, '""')
            field_lines.append("    %s: %s = %s" % (f.name, f.type, default))
            if f.type == "int":
                check_lines.append(
                    "        if isinstance(self.{n}, bool) or not isinstance(self.{n}, int):\n"
                    '            errors.append("{n} must be an integer")'.format(n=f.name)
                )
            elif f.type == "float":
                check_lines.append(
                    "        if not isinstance(self.{n}, (int, float)) or isinstance(self.{n}, bool):\n"
                    '            errors.append("{n} must be a number")'.format(n=f.name)
                )
        body = [
            "@dataclass",
            "class %s:" % cls,
            '    """%s entity model."""' % cls,
            "    id: str = \"\"",
        ]
        body.extend(field_lines or ['    name: str = ""'])
        body += [
            "",
            "    def validate(self) -> List[str]:",
            "        errors: List[str] = []",
            '        if not str(self.name).strip():',
            '            errors.append("name is required")',
        ]
        body.extend(check_lines)
        body += [
            "        return errors",
            "",
            "    def to_dict(self) -> Dict[str, Any]:",
            "        return asdict(self)",
            "",
            "    @classmethod",
            '    def from_dict(cls, data: Dict[str, Any]) -> "%s":' % cls,
            "        known = {f.name for f in fields(cls)} - {\"id\"}",
            "        kwargs = {}",
            "        for key in known:",
            "            ftype = next(f.type for f in fields(cls) if f.name == key)",
            "            default = {_defaults}[ftype]".replace(
                "{_defaults}",
                '{"str": "", "int": 0, "float": 0.0, "bool": False}',
            ),
            "            kwargs[key] = data.get(key, default)",
            "        return cls(**kwargs)",
            "",
            "",
        ]
        classes.append("\n".join(body))
    registry = ",\n    ".join(
        '"%s": %s' % (m.name, _class_name(m.name)) for m in plan.data_model
    )
    plurals = ",\n    ".join(
        '"%s": "%s"' % (_plural(m.name), m.name) for m in plan.data_model
    )
    return "\n".join(
        [
            '"""Entity models: validation and serialization.',
            "",
            "Design law: validation lives here, never in routes. Routes translate",
            "HTTP; models decide truth.",
            '"""',
            "from __future__ import annotations",
            "",
            "from dataclasses import asdict, dataclass, fields",
            "from typing import Any, Dict, List",
            "",
            "",
        ]
        + classes
        + [
            "REGISTRY = {",
            "    %s," % registry,
            "}",
            "",
            "PLURALS = {",
            "    %s," % plurals,
            "}",
            "",
        ]
    )


def _gen_store(plan: BuildPlan) -> str:
    return "\n".join(
        [
            '"""Atomic JSON file store.',
            "",
            "The ONLY module that touches the data file. Writes go to a temp file",
            "and are atomically renamed, so a crash never leaves half a database.",
            '"""',
            "from __future__ import annotations",
            "",
            "import json",
            "import os",
            "import tempfile",
            "from typing import Any, Dict, List, Optional",
            "",
            "",
            "def _discard_tmp(path: str) -> None:",
            '    """Remove a temp file this store created. Refuses anything not *.tmp.',
            "",
            "    The verifier allows os.remove ONLY here, and only because of",
            '    this guard — checked by AST, not by trust."""',
            '    if not path.endswith(".tmp"):',
            '        raise ValueError("refusing to discard non-temp path")',
            "    try:",
            "        os.remove(path)",
            "    except OSError:",
            "        pass",
            "",
            "",
            "class Store:",
            '    """JSON document store: {entity: [records]}."""',
            "",
            "    def __init__(self, path: str) -> None:",
            "        self.path = path",
            "        self._data: Optional[Dict[str, Any]] = None",
            "",
            "    def _load(self) -> Dict[str, Any]:",
            "        if self._data is None:",
            "            try:",
            '                with open(self.path, encoding="utf-8") as fh:',
            "                    self._data = json.load(fh)",
            "            except (OSError, ValueError):",
            "                self._data = {}",
            "        return self._data",
            "",
            "    def save(self) -> None:",
            "        data = self._load()",
            "        directory = os.path.dirname(os.path.abspath(self.path))",
            '        fd, tmp = tempfile.mkstemp(dir=directory, suffix=".tmp")',
            "        try:",
            '            with os.fdopen(fd, "w", encoding="utf-8") as fh:',
            "                json.dump(data, fh, indent=2)",
            "            os.replace(tmp, self.path)",
            "        except BaseException:",
            "            _discard_tmp(tmp)",
            "            raise",
            "",
            "    def _next_id(self, entity: str) -> str:",
            '        seq = self._load().setdefault("_seq", {})',
            "        seq[entity] = int(seq.get(entity, 0)) + 1",
            "        return str(seq[entity])",
            "",
            "    def list(self, entity: str) -> List[Dict[str, Any]]:",
            "        return list(self._load().get(entity, []))",
            "",
            "    def create(self, entity: str, record: Dict[str, Any]) -> Dict[str, Any]:",
            "        record = dict(record)",
            '        record["id"] = self._next_id(entity)',
            "        self._load().setdefault(entity, []).append(record)",
            "        self.save()",
            "        return record",
            "",
            "    def get(self, entity: str, rid: str) -> Optional[Dict[str, Any]]:",
            "        for rec in self._load().get(entity, []):",
            '            if str(rec.get("id")) == str(rid):',
            "                return rec",
            "        return None",
            "",
            "    def update(",
            "        self, entity: str, rid: str, record: Dict[str, Any]",
            "    ) -> Optional[Dict[str, Any]]:",
            "        items = self._load().get(entity, [])",
            "        for i, rec in enumerate(items):",
            '            if str(rec.get("id")) == str(rid):',
            "                record = dict(record)",
            '                record["id"] = str(rid)',
            "                items[i] = record",
            "                self.save()",
            "                return record",
            "        return None",
            "",
            "    def delete(self, entity: str, rid: str) -> bool:",
            "        items = self._load().get(entity, [])",
            "        for i, rec in enumerate(items):",
            '            if str(rec.get("id")) == str(rid):',
            "                del items[i]",
            "                self.save()",
            "                return True",
            "        return False",
            "",
        ]
    )


def _gen_auth(plan: BuildPlan) -> str:
    return "\n".join(
        [
            '"""Bearer-token auth.',
            "",
            "Tokens live in a file (one per line); comparison is constant-time.",
            "Auth wraps routes — it never lives inside them.",
            '"""',
            "from __future__ import annotations",
            "",
            "import hmac",
            "from typing import Dict, List",
            "",
            "",
            "def load_tokens(path: str) -> List[str]:",
            "    try:",
            '        with open(path, encoding="utf-8") as fh:',
            "            return [",
            "                line.strip()",
            "                for line in fh",
            '                if line.strip() and not line.startswith("#")',
            "            ]",
            "    except OSError:",
            "        return []",
            "",
            "",
            "def authorized(headers: Dict[str, str], tokens: List[str]) -> bool:",
            '    auth = headers.get("Authorization") or headers.get("authorization") or ""',
            '    if not auth.lower().startswith("bearer "):',
            "        return False",
            "    presented = auth[7:].strip()",
            "    return any(hmac.compare_digest(presented, t) for t in tokens)",
            "",
        ]
    )


def _gen_routes(plan: BuildPlan) -> str:
    return "\n".join(
        [
            '"""HTTP route handlers: one uniform CRUD family per entity.',
            "",
            "Routes translate HTTP; models decide truth; the store owns the file.",
            '"""',
            "from __future__ import annotations",
            "",
            "from typing import Any, Dict, List, Tuple",
            "",
            "from api.models import PLURALS, REGISTRY",
            "from auth import authorized",
            "",
            "",
            "def _error(status: int, code: str, detail: str):",
            '    return (status, {"error": code, "detail": detail})',
            "",
            "",
            "def handle(store, tokens, method, segments, body, headers):",
            '    """Dispatch one request. Returns (status, json_payload)."""',
            '    if segments == ["api", "health"]:',
            '        return 200, {"ok": True, "entities": sorted(PLURALS)}',
            "    if not authorized(headers or {}, tokens or []):",
            '        return _error(401, "unauthorized", "valid bearer token required")',
            '    if len(segments) < 2 or segments[0] != "api":',
            '        return _error(404, "not_found", "unknown route")',
            "    plural = segments[1]",
            "    if plural not in PLURALS:",
            '        return _error(404, "not_found", "unknown entity %r" % plural)',
            "    entity = PLURALS[plural]",
            "    cls = REGISTRY[entity]",
            '    if method == "GET" and len(segments) == 2:',
            '        return (200, {"data": store.list(entity)})',
            '    if method == "POST" and len(segments) == 2:',
            "        if not isinstance(body, dict):",
            '            return _error(400, "bad_request", "JSON object required")',
            "        obj = cls.from_dict(body)",
            "        errors = obj.validate()",
            "        if errors:",
            '            return _error(422, "validation_failed", "; ".join(errors))',
            "        return (201, store.create(entity, obj.to_dict()))",
            "    if len(segments) == 3:",
            "        rid = segments[2]",
            '        if method == "GET":',
            "            rec = store.get(entity, rid)",
            "            return (200, rec) if rec else _error(",
            '                404, "not_found", "no such %s" % entity',
            "            )",
            '        if method == "PUT":',
            "            if not isinstance(body, dict):",
            '                return _error(400, "bad_request", "JSON object required")',
            "            obj = cls.from_dict(body)",
            "            errors = obj.validate()",
            "            if errors:",
            '                return _error(422, "validation_failed", "; ".join(errors))',
            "            rec = store.update(entity, rid, obj.to_dict())",
            "            return (200, rec) if rec else _error(",
            '                404, "not_found", "no such %s" % entity',
            "            )",
            '        if method == "DELETE":',
            "            if store.delete(entity, rid):",
            '                return (200, {"deleted": True})',
            '            return _error(404, "not_found", "no such %s" % entity)',
            '    return _error(405, "method_not_allowed", "unsupported method/path")',
            "",
        ]
    )


def _gen_entry_webapi(plan: BuildPlan) -> str:
    title = plan.app_slug.replace("-", " ").title()
    return "\n".join(
        [
            '"""%s — generated by LEVI builders (plan-driven, deterministic).' % title,
            "",
            "Provenance: every line below was produced by the builder from your",
            "prompt; anything you add yourself is yours. Runs on stdlib only —",
            "no installs, no network, no accounts.",
            '"""',
            "from __future__ import annotations",
            "",
            "import argparse",
            "import json",
            "import os",
            "import sys",
            "from http.server import BaseHTTPRequestHandler, HTTPServer",
            "from urllib.parse import urlparse",
            "",
            "sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))",
            "",
            "from api.routes import handle",
            "from auth import load_tokens",
            "from migrations.m0001_init import apply as migrate_init",
            "from store import Store",
            "",
            "",
            "class Handler(BaseHTTPRequestHandler):",
            "    store = None",
            "    tokens = []",
            "",
            "    def _send(self, status, payload):",
            '        data = json.dumps(payload).encode("utf-8")',
            "        self.send_response(status)",
            '        self.send_header("Content-Type", "application/json")',
            '        self.send_header("Content-Length", str(len(data)))',
            "        self.end_headers()",
            "        self.wfile.write(data)",
            "",
            "    def _dispatch(self, method):",
            "        try:",
            '            length = int(self.headers.get("Content-Length") or 0)',
            "        except ValueError:",
            "            length = 0",
            "        raw = self.rfile.read(length) if length > 0 else b\"\"",
            "        if raw:",
            "            try:",
            '                body = json.loads(raw.decode("utf-8"))',
            "            except ValueError:",
            "                body = None",
            "            if body is None:",
            '                return self._send(400, {"error": "bad_request",',
            '                                         "detail": "invalid JSON"})',
            "        else:",
            "            body = {}",
            "        segments = [s for s in urlparse(self.path).path.split(\"/\") if s]",
            "        status, payload = handle(",
            "            Handler.store,",
            "            Handler.tokens,",
            "            method,",
            "            segments,",
            "            body,",
            "            dict(self.headers),",
            "        )",
            "        self._send(status, payload)",
            "",
            '    def do_GET(self): self._dispatch("GET")',
            '    def do_POST(self): self._dispatch("POST")',
            '    def do_PUT(self): self._dispatch("PUT")',
            '    def do_DELETE(self): self._dispatch("DELETE")',
            "",
            "    def log_message(self, *args):  # keep stdout clean for scripts",
            "        pass",
            "",
            "",
            "def main() -> None:",
            '    parser = argparse.ArgumentParser(description="%s (LEVI builders)")' % title,
            '    parser.add_argument("--port", type=int, default=8080)',
            '    parser.add_argument("--data", default=os.environ.get("DATA_FILE", "data.json"))',
            '    parser.add_argument("--tokens", default=os.environ.get("AUTH_TOKENS_FILE", ".tokens"))',
            "    args = parser.parse_args()",
            '    root = os.path.dirname(os.path.abspath(__file__))',
            "    data_path = args.data if os.path.isabs(args.data) else os.path.join(root, args.data)",
            "    tokens_path = (",
            "        args.tokens if os.path.isabs(args.tokens) else os.path.join(root, args.tokens)",
            "    )",
            '    migrate_init(data_path, tokens_path)',
            "    Handler.store = Store(data_path)",
            "    Handler.tokens = load_tokens(tokens_path)",
            '    server = HTTPServer(("127.0.0.1", args.port), Handler)',
            '    print("serving %s on 127.0.0.1:%%d" %% args.port, flush=True)' % plan.app_slug,
            '    print("token file: %s" % tokens_path, flush=True)',
            "    try:",
            "        server.serve_forever()",
            "    except KeyboardInterrupt:",
            "        pass",
            "",
            "",
            'if __name__ == "__main__":',
            "    main()",
            "",
        ]
    )


def _gen_migration(plan: BuildPlan) -> str:
    entities_json = json.dumps({m.name: [] for m in plan.data_model})
    return "\n".join(
        [
            '"""Schema bootstrap migration (m0001).',
            "",
            "Applied when the data file is missing. Migrations are the only",
            "way schema changes happen — destructive operations are refused",
            "by the verifier, never silently applied.",
            '"""',
            "from __future__ import annotations",
            "",
            "import json",
            "import os",
            "import secrets",
            "",
            "",
            "def apply(data_path: str, tokens_path: str) -> None:",
            '    """Create the data file and token file if they are missing.',
            "",
            "    The first-boot token is random per deployment (not derived from",
            "    anything guessable); it is printed and saved to the token file.",
            '    """',
            "    if not os.path.exists(data_path):",
            '        with open(data_path, "w", encoding="utf-8") as fh:',
            "            json.dump(%s, fh, indent=2)" % entities_json,
            '            fh.write("\\n")',
            "    if not os.path.exists(tokens_path):",
            '        with open(tokens_path, "w", encoding="utf-8") as fh:',
            '            fh.write("levi-" + secrets.token_hex(16) + "\\n")',
            "        os.chmod(tokens_path, 0o600)",
            "",
        ]
    )


