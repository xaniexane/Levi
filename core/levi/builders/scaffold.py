            "        count = to_jsonl(kept, args.output)",
            "    else:",
            "        count = to_stdout(kept)",
            "    write_offset(args.state, seen)",
            '    print("pipeline done: %d kept of %d seen" % (count, seen), file=sys.stderr)',
            "",
            "",
            'if __name__ == "__main__":',
