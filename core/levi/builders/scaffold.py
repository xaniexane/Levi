class ScaffoldEngine:
    """Proposer twin: plan -> deterministic multi-module project."""

    def __init__(
        self,
        prompt: str,
        _fault_hook: Optional[Callable[[int, Dict[str, str]], None]] = None,
    ) -> None:
        if not prompt or not prompt.strip():
            raise ValueError("prompt must not be empty")
        self.prompt = prompt.strip()
        self.build_plan = _plan_prompt(self.prompt)
        self.prompt_hash = self.build_plan.prompt_hash
        self.seed = self.build_plan.seed
        self.app_slug = self.build_plan.app_slug
        self.entities = self.build_plan.entities
        self.domain = self.build_plan.domain
        self.palette = _PALETTES[self.seed % len(_PALETTES)]
        self._fault_hook = _fault_hook

    def _plan_for(self, repair_level: int) -> BuildPlan:
        # Repair NEVER changes the requested domain, entities, or capability.
        # A retry that silently downgrades complexity is a lie wearing a
        # success badge; a repair we cannot make honestly becomes
        # OWNER_DECISION_NEEDED at the bound. Level 1 sanitizes identifiers
        # (the realistic codegen-fault class); higher levels regenerate the
        # same plan, which is meaningful for transient faults (port clashes,
        # server-start timing in the smoke gate) and harmless otherwise.
        plan = self.build_plan
        if repair_level >= 1:
            # Repair pass: strictly sanitize identifiers, strip surprises.
            entities = [re.sub(r"[^a-z_]", "", e) or "item" for e in plan.entities]
            data_model = [
                dataclasses.replace(m, name=name)
                for m, name in zip(plan.data_model, entities)
            ]
            plan = dataclasses.replace(plan, entities=entities, data_model=data_model)
        return plan

    def generate(self, repair_level: int = 0) -> Dict[str, str]:
        """Return {relative_path: content}. Deterministic in prompt."""
        plan = self._plan_for(repair_level)
        files: Dict[str, str] = {}
        for module in plan.modules:
            files[module.path] = _emit_module(plan, module.path, module.kind)
        files["README.md"] = _readme(plan)
        files["theme.yaml"] = _theme(plan, self.palette)
        files[".provenance.json"] = _provenance(plan, [])
        return files

    def apply_fault_hook(self, attempt: int, files: Dict[str, str]) -> None:
        if self._fault_hook is not None:
            self._fault_hook(attempt, files)
