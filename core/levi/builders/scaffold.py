def _gen_sources(plan: BuildPlan) -> str:
    return "\n".join(
        [
            '"""Record producers. Sources own input I/O — nothing else reads files."""',
            "from __future__ import annotations",
            "",
            "import json",
            "import sys",
            "from typing import Any, Dict, Iterator, Optional",
            "",
            "",
            "def iter_jsonl(path: str):",
            '    """Yield one dict per line; skip blank and broken lines."""',
            '    with open(path, encoding="utf-8") as fh:',
            "        for line in fh:",
            "            line = line.strip()",
            "            if not line:",
            "                continue",
            "            try:",
            "                record = json.loads(line)",
            "            except ValueError:",
            "                continue",
            "            if isinstance(record, dict):",
            "                yield record",
            "",
            "",
            "def iter_records(path: Optional[str]):",
            '    """Yield records from a JSONL file, or from stdin when path is "-"."""',
            '    if path is None or path == "-":',
            "        for line in sys.stdin:",
            "            line = line.strip()",
            "            if not line:",
            "                continue",
            "            try:",
            "                record = json.loads(line)",
            "            except ValueError:",
            "                continue",
            "            if isinstance(record, dict):",
            "                yield record",
            "    else:",
            "        yield from iter_jsonl(path)",
            "",
        ]
    )


def _gen_stages(plan: BuildPlan) -> str:
    blocks = []
    for m in plan.data_model:
        blocks.append(
            "\n".join(
                [
                    "def clean_%s(record):" % m.name,
                    '    """Pure transform for %s records: strip strings, drop empties."""' % m.name,
                    "    if not isinstance(record, dict):",
                    "        return None",
                    "    cleaned = {}",
                    "    for key, value in record.items():",
                    "        cleaned[key] = value.strip() if isinstance(value, str) else value",
                    '    if not str(cleaned.get("name", "")).strip():',
                    "        return None",
                    "    return cleaned",
                    "",
                    "",
                ]
            )
        )
    return (
        '"""Pure transforms: records in, records out, no I/O.\n\n'
        "Design law: stages never touch the filesystem. Impure stages are a defect.\n"
        '"""\n'
        "from __future__ import annotations\n\n\n" + "".join(blocks)
    )


def _gen_sinks(plan: BuildPlan) -> str:
    return "\n".join(
        [
            '"""Record consumers. Sinks own output I/O."""',
            "from __future__ import annotations",
            "",
            "import json",
            "import sys",
            "",
            "",
            "def to_jsonl(records, path):",
            "    count = 0",
            '    with open(path, "w", encoding="utf-8") as fh:',
            "        for record in records:",
            "            fh.write(json.dumps(record) + \"\\n\")",
            "            count += 1",
            "    return count",
            "",
            "",
            "def to_stdout(records):",
            "    count = 0",
            "    for record in records:",
            '        sys.stdout.write(json.dumps(record) + "\\n")',
            "        count += 1",
            "    return count",
            "",
        ]
    )


