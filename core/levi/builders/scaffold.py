def _theme(plan: BuildPlan, palette: Dict[str, str]) -> str:
    directives_yaml = "".join(
        '  - "%s"\n' % d.replace('"', "'") for d in plan.design_directives
    )
    return _THEME_TEMPLATE.substitute(
        title=plan.app_slug.replace("-", " ").title(),
        directives_yaml=directives_yaml or '  - "none"\n',
        provenance=_PROVENANCE,
        **palette,
    )


def _entry_name(plan: BuildPlan) -> str:
    for module in plan.modules:
        if module.kind == "entry":
            return module.path
    return "app.py"


def _readme(plan: BuildPlan) -> str:
    title = plan.app_slug.replace("-", " ").title()
    lines = [
        "# %s" % title,
        "",
        "Generated by **LEVI builders** from your prompt — deterministic,",
        "no credits, no cloud. Domain: `%s`." % plan.domain,
        "Every file carries provenance: builder-made unless you changed it.",
        "",
        "## Module map",
        "",
    ]
    for module in plan.modules:
        lines.append("- `%s` — %s" % (module.path, module.purpose))
    if plan.api_surface:
        lines += ["", "## API surface", ""]
        for route in plan.api_surface:
            lines.append("- `%s`" % route)
    if plan.domain == "web-api":
        lines += [
            "",
            "## Auth",
            "",
            "All routes require a bearer token. The token file is created",
            "on first boot (see `.env.example`); pass it as:",
            "",
            "```sh",
            'curl -H "Authorization: Bearer <token>" localhost:8080/api/<entity>',
            "```",
        ]
    lines += [
        "",
        "## Run it",
        "",
        "```sh",
        "python3 %s --port 8080" % _entry_name(plan),
        "```",
        "",
        "## Verify it",
        "",
        "```sh",
        "python3 -m compileall .",
    ]
    for module in plan.modules:
        if module.kind == "test":
            lines.append("python3 %s" % module.path)
    lines += [
        "```",
        "",
        "Entities: %s." % ", ".join(plan.entities),
        "",
        "## Customize",
        "",
        "Edit `theme.yaml` — structured, safe theming on every surface",
        "(Myspace-style customization, no code injection possible).",
        "",
    ]
    return "\n".join(lines)


def _provenance(plan: BuildPlan, iterations: List[Dict]) -> str:
    record = {
        "provenance": _PROVENANCE,
        "prompt": plan.prompt,
        "prompt_sha256": plan.prompt_hash,
        "seed": plan.seed,
        "app": plan.app_slug,
        "domain": plan.domain,
        "entities": plan.entities,
        "modules": [m.path for m in plan.modules],
        "api_surface": plan.api_surface,
        "iterations": iterations,
    }
    return json.dumps(record, indent=2, sort_keys=True) + "\n"


