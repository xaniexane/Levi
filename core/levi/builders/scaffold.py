_PACKAGE_TEMPLATE = '"""{purpose}\n"""\n'


def _emit_module(plan: BuildPlan, path: str, kind: str) -> str:
    domain = plan.domain
    if kind == "package":
        purpose = next(
            (m.purpose for m in plan.modules if m.path == path), "Package marker."
        )
        return _PACKAGE_TEMPLATE.format(purpose=purpose)
    if kind == "test":
        return _emit_test(plan, path)
    if domain == "web-api":
        return {
            "entry": _gen_entry_webapi,
            "models": _gen_models,
            "routes": _gen_routes,
            "store": _gen_store,
            "auth": _gen_auth,
            "migration": _gen_migration,
            "config": _gen_env_example,
        }[kind](plan)
    if domain == "realtime":
        if kind == "entry":
            return _gen_entry_realtime(plan)
        if kind == "events":
            return _gen_events(plan)
        if kind == "models":
            return _gen_event_models(plan)
        if kind == "store":
            return _gen_store(plan)
    if domain == "data-pipeline":
        if kind == "entry":
            return _gen_entry_pipeline(plan)
        if kind == "source":
            return _gen_sources(plan)
        if kind == "stage":
            return _gen_stages(plan)
        if kind == "sink":
            return _gen_sinks(plan)
        if kind == "store":
            return _gen_state(plan)
    if domain == "cli-tool":
        if kind == "entry":
            return _gen_entry_cli(plan)
        if kind == "core":
            return _gen_core_cli(plan)
    if domain == "general":
        if kind == "entry":
            return _gen_entry_general(plan)
    raise ValueError("no generator for domain=%r kind=%r" % (domain, kind))


def _emit_test(plan: BuildPlan, path: str) -> str:
    domain = plan.domain
    name = path.rsplit("/", 1)[-1]
    if name == "test_models.py":
        return _gen_test_models(plan)
    if name == "test_api.py":
        return _gen_test_api(plan)
    if name == "test_events.py":
        return _gen_test_events(plan)
    if name == "test_stages.py":
        return _gen_test_stages(plan)
    if name == "test_core.py":
        return _gen_test_core(plan)
    if name == "test_smoke.py":
        if domain == "data-pipeline":
            return _gen_test_smoke_pipeline(plan)
