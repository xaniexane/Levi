            "",
            "import argparse",
            "import os",
            "import sys",
            "",
            "sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))",
            "",
            "from sinks import to_jsonl, to_stdout",
            "from sources import iter_records",
            "from stages import clean_%s" % entity,
            "from state import read_offset, write_offset",
