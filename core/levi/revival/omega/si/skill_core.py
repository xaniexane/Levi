def scaffold_skill(name: str, capability: str) -> Dict[str, Any]:
    """Build the three-file scaffold; ``ok`` is False with reasons if refused.

    Never raises on bad input — the refusal is part of the return value so
    callers (and the CLI) can report it plainly.
    """
    errors: List[str] = []
    if not isinstance(name, str) or not _NAME_RE.match(name or ""):
        errors.append(
            f"invalid skill name {name!r}: use a slug "
            "(lowercase letters, digits, dashes, underscores)"
        )
    if not isinstance(capability, str) or not capability.strip():
        errors.append("capability must be a non-empty string")
    if errors:
        return {"ok": False, "name": name, "files": {}, "errors": errors}
    module = name.replace("-", "_")
    files = {
        f"{name}/SKILL.md": _skill_md(name, capability),
        f"{name}/skill.py": _skill_py(name, capability),
        f"{name}/tests/test_{module}.py": _test_skeleton_py(name, capability),
    }
    return {"ok": True, "name": name, "files": files, "errors": []}


# ---------------------------------------------------------------------------
# Skill registry + guarded execution: Omega's hands in the bloodstream.
#
# INVARIANT: No skill runs without a declared risk tier and a receipt.
# Every run is challengeable.
# ---------------------------------------------------------------------------

#: name -> {"capability": str, "risk": tier, "runs": int}
_REGISTRY: Dict[str, Dict[str, Any]] = {}

#: name -> fn(task) -> dict. Real procedures attach here via
#: attach_procedure(); without one, run_skill() executes the skill's
#: *declared* capability and says so honestly.
_PROCEDURES: Dict[str, Callable[[str], Dict[str, Any]]] = {}


def register_skill(
    name: str,
    capability: str,
    risk: str = "elevated",
    approved_by: Any = None,
    substrate: Any = None,
) -> Dict[str, Any]:
    """Declare a skill in the registry; optionally record it in the substrate.

    Validates the name (non-empty) and the risk tier (a real tier —
    ``ValueError`` otherwise). Re-registering the same name overwrites the
    previous entry, runs counter included — a skill's declaration is
    current-state, not history.

    When ``substrate`` is given, a ``skill_registered`` receipt is recorded
    at the declared risk tier. Elevated and above need ``approved_by`` —
    the substrate raises ``ValueError`` without it. That is correct
    behavior: an unapproved elevated registration must fail loudly, never
    slip in silently.
    """
    if not isinstance(name, str) or not name.strip():
        raise ValueError("skill name must be a non-empty string")
    tiers = _sub().RISK_ORDER
    if risk not in tiers:
        raise ValueError(f"unknown risk tier: {risk!r} (want one of {tiers})")
    _REGISTRY[name] = {"capability": capability, "risk": risk, "runs": 0}
    if substrate is not None:
        substrate.record_receipt(
            organ="skill",
            kind="skill_registered",
            payload={"name": name, "capability": capability, "risk": risk},
            risk=risk,
            approved_by=approved_by,
        )
    return {"ok": True, "name": name, "risk": risk}


def get_skill(name: str) -> Any:
    """The registry entry for ``name``, or None. A copy — mutating the
    result does not touch the registry."""
    entry = _REGISTRY.get(name)
    return dict(entry) if entry is not None else None


def list_skills() -> List[str]:
    """Names of all registered skills."""
    return list(_REGISTRY)


def attach_procedure(name: str, fn: Callable[[str], Dict[str, Any]]) -> None:
    """Give a registered skill a real body: ``fn(task) -> dict``.

    Only for names already in the registry (``KeyError`` otherwise) — a
    procedure must always hang off a declared skill with a declared risk
    tier. This is how the daemon, or a real skill implementation, turns a
    declaration into working hands.
    """
    if name not in _REGISTRY:
        raise KeyError(f"unknown skill {name!r}: register it first")
    if not callable(fn):
        raise ValueError("procedure must be callable")
    _PROCEDURES[name] = fn


def _result_summary(result: Any) -> str:
    """Small honest summary of a run result for the receipt payload."""
    if isinstance(result, dict):
        text = result.get("summary") or f"keys={sorted(result)}"
    else:
        text = str(result)
    return str(text)[:280]


def run_skill(name: str, task: str) -> Dict[str, Any]:
    """Execute a registered skill's local procedure and return the payload.

    If a real procedure was attached with ``attach_procedure()`` it runs.
    Otherwise the run executes the skill's *declared* capability and says
    so honestly (``"declared": True`` in the payload) — a skill never
    fakes a result it cannot produce. Unknown names raise ``KeyError``
    loudly; the guarded path (``run_skill_guarded``) turns that into a
    refusal instead.
    """
    entry = _REGISTRY.get(name)
    if entry is None:
        raise KeyError(f"unknown skill {name!r}: register it first")
    proc = _PROCEDURES.get(name)
    if proc is not None:
        return proc(task)
    return {
        "ok": True,
        "skill": name,
        "task": task,
        "summary": f"{name}: {entry['capability']}",
        "declared": True,
    }


def run_skill_guarded(
    substrate: Any,
    name: str,
    task: str,
    approved_by: Any = None,
) -> Dict[str, Any]:
    """The only execution path: risk-ceiling check, approval gate, receipt.

    - Unknown name -> ``{"ok": False, "refusal": "unknown skill"}``.
    - The ceiling is ``substrate.ceiling_for("skill", action_risk=...)``:
      the skill organ's own declared ceiling is elevated, so the
      strictest-tier-inheritance law means every skill run is at least
      elevated — approval is always required.
    - Without ``approved_by`` -> refusal. A ``skill_refusal`` receipt is
      recorded, but at ``"standard"`` — never at the elevated ceiling.
      Reason: recording the refusal at elevated would itself demand an
      approval, the classic Catch-22 (you would need permission to record
      that you lacked permission). A refusal is an observation, not an
      action in the world, so standard is the honest tier.
    - A run with no substrate is refused outright: the invariant says no
      skill runs without a receipt, and a receipt needs the bloodstream.
    - On success: the skill runs, the registry ``runs`` counter
      increments, a ``skill_run`` receipt is recorded at the ceiling with
      the approval attached, and the receipt id is returned. The receipt
      is challengeable — the daemon quarantines skill results by
      challenging it (interrogation path).
    """
    entry = _REGISTRY.get(name)
    if entry is None:
        return {"ok": False, "refusal": "unknown skill"}
    sub = _sub()
    ceiling = sub.ceiling_for("skill", action_risk=entry["risk"])
    if sub.requires_approval(ceiling) and not approved_by:
        if substrate is not None:
            substrate.record_receipt(
                organ="skill",
                kind="skill_refusal",
                payload={
                    "skill": name,
                    "task": task,
                    "ceiling": ceiling,
                    "reason": "approval required",
                },
                risk="standard",  # see docstring: refusal is an observation
                approved_by=None,
            )
        return {"ok": False, "refusal": "approval required", "ceiling": ceiling}
    if substrate is None:
        return {
            "ok": False,
            "refusal": "no substrate: a run receipt cannot be recorded",
        }
    result = run_skill(name, task)
    entry["runs"] += 1
    receipt = substrate.record_receipt(
        organ="skill",
        kind="skill_run",
        payload={
            "skill": name,
            "task": task,
            "result": _result_summary(result),
        },
        risk=ceiling,
        approved_by=approved_by,
    )
    return {
        "ok": True,
        "result": result,
        "receipt_id": receipt.id,
        "ceiling": ceiling,
    }
