def _gen_skill(blueprint: Dict[str, Any]) -> Dict[str, str]:
    name = blueprint["name"]
    title = blueprint["title"]
    skill_md = f'''---
skill_id: "{_yaml_str(name)}"
name: "{_yaml_str(title)}"
description: "{_yaml_str(blueprint["prompt"][:140])}"
version: "0.1.0"
risk: "info"
permissions: []
requires_confirmation: false
tags: ["generated", "revival"]
source: "levi-revival-omega/alpha"
---
# {title}

## Purpose

{_yaml_str(blueprint["prompt"][:200])}

Scaffolded by LEVI's Alpha compiler from a plain-language request. Fill in the
steps below with the real procedure, then wire `skill.py` to make the skill
executable.

## When to use

- When the request matches the purpose above.
- When a small, repeatable capability is needed instead of a one-off answer.

## Steps

1. Parse the request arguments (`python skill.py --help`).
2. Do the work locally — local-first, stdlib only, no paid APIs.
3. Return a short human-readable summary.

## Output contract

- On success: one-line summary plus the result payload.
- On failure: a clear reason and what to do next.

## Operating rules

1. Never collect or store credentials (keys, secrets, passwords, tokens).
2. Never send user data off-machine; local-first always.
3. Defensive only — detection, analysis, hardening. Nothing offensive.

## Honesty notes

- Risk `info` is a starter guess — verify before real use.
- A skill that cannot explain itself in one line is not ready.
'''
    skill_py = (
        '''"""{TITLE} — LEVI skill scaffold (stdlib only)."""
{PY_HEADER}
from __future__ import annotations

import argparse
import json
import sys

SKILL_ID = "{SKILL_ID}"


def run_skill(task: str) -> dict:
    """Do the skill's work locally and return a result payload.

    Local-first: stdlib only, no network, no credentials, no paid APIs.
    Fill in the real procedure here.
    """
    return {
        "skill": SKILL_ID,
        "task": task,
        "summary": f"TODO: implement {SKILL_ID}",
        "ok": True,
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog=SKILL_ID, description="{TITLE}")
    parser.add_argument("task", nargs="?", default="",
                        help="the task for this skill")
    parser.add_argument("--json", action="store_true",
                        help="print the raw result payload")
    args = parser.parse_args(argv)
    result = run_skill(args.task)
    if args.json:
        print(json.dumps(result, indent=2))
    else:
        print(result["summary"])
    return 0 if result.get("ok") else 1


if __name__ == "__main__":
    sys.exit(main())
'''.replace("{TITLE}", title)
        .replace("{SKILL_ID}", name)
        .replace("{PY_HEADER}", _py_header(blueprint, "skill"))
    )
    return {f"{name}/SKILL.md": skill_md, f"{name}/skill.py": skill_py}


