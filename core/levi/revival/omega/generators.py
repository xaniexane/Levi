"""Alpha revival: the no-code compiler's generator registry, LEVI-native.

Omega's Alpha compiled Echo blueprints into working products through a
registry of named generators (webpage, backend, CLI, MCP server, ...).
This module is that mechanism from scratch: register a generator per
product type, then compile any validated blueprint into real scaffold
files — returned as ``{path: content}`` so the caller decides where
they land.

Public surface:

- ``Generator`` — ``name``, ``title``, ``description``,
  ``product_types`` and ``generate(blueprint) -> Dict[str, str]``.
- ``register(generator)`` / ``get(name)`` / ``registered()``.
- ``generators_for(blueprint)`` — generators matching the blueprint's
  product types, in blueprint order.
- ``compile_blueprint(blueprint)`` — validate, then run every matching
  generator; returns ``{"ok", "files", "errors", "blueprint"}``.

Six LEVI-native generators ship built in: ``webpage``, ``cli``,
``api`` (FastAPI), ``mcp_server``, ``automation``, ``skill``. Generated code
is honest about its provenance (header comment) and its dependencies.

Defensive notes:

- ``compile_blueprint`` validates first via ``blueprint.validate_blueprint``
  and refuses invalid input instead of generating garbage.
- A failing generator never aborts the compile: its error is recorded in
  ``errors`` and the remaining generators still run.
- Duplicate registration is a ``ValueError`` — silent overwrites hide
  bugs; rename or unregister explicitly.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List

from .blueprint import ORIGIN as BLUEPRINT_ORIGIN
from .blueprint import validate_blueprint

ORIGIN = "levi-revival-omega/alpha"

GenerateFn = Callable[[Dict[str, Any]], Dict[str, str]]


@dataclass
class Generator:
    name: str
    title: str
    description: str
    product_types: List[str]
    generate: GenerateFn = field(repr=False)


_REGISTRY: Dict[str, Generator] = {}


def register(generator: Generator) -> Generator:
    if not generator.name or not isinstance(generator.name, str):
        raise ValueError("generator must have a non-empty string name")
    if generator.name in _REGISTRY:
        raise ValueError(f"generator already registered: {generator.name!r}")
    _REGISTRY[generator.name] = generator
    return generator


def unregister(name: str) -> None:
    if name not in _REGISTRY:
        raise ValueError(f"unknown generator: {name!r}")
    del _REGISTRY[name]


def get(name: str) -> Generator:
    try:
        return _REGISTRY[name]
    except KeyError:
        raise ValueError(f"unknown generator: {name!r}") from None


def registered() -> List[str]:
    return sorted(_REGISTRY)


def generators_for(blueprint: Dict[str, Any]) -> List[Generator]:
    wanted = blueprint.get("product_types", []) if isinstance(blueprint, dict) else []
    found: List[Generator] = []
    for ptype in wanted:
        for gen in _REGISTRY.values():
            if ptype in gen.product_types and gen not in found:
                found.append(gen)
    return found


def compile_blueprint(blueprint: Dict[str, Any]) -> Dict[str, Any]:
    """Validate a blueprint, then run every matching generator."""
    check = validate_blueprint(blueprint)
    if not check["ok"]:
        return {
            "ok": False,
            "files": {},
            "errors": [f"invalid blueprint: {e}" for e in check["errors"]],
            "blueprint": blueprint if isinstance(blueprint, dict) else {},
        }
    files: Dict[str, str] = {}
    errors: List[str] = []
    for gen in generators_for(blueprint):
        try:
            produced = gen.generate(blueprint)
        except Exception as exc:  # noqa: BLE001 - recorded, not raised
            errors.append(f"{gen.name}: {exc}")
            continue
        if not isinstance(produced, dict):
            errors.append(
                f"{gen.name}: generator must return dict, got {type(produced).__name__}"
            )
            continue
        for path, content in produced.items():
            if path in files:
                errors.append(f"{gen.name}: path collision on {path!r}")
                continue
            files[path] = content
    return {"ok": not errors, "files": files, "errors": errors, "blueprint": blueprint}


def _header(blueprint: Dict[str, Any], kind: str) -> str:
    return (
        f"Generated by LEVI revival/omega ({BLUEPRINT_ORIGIN} -> {ORIGIN})\n"
        f"kind: {kind} | app: {blueprint['name']} | "
        f"prompt: {blueprint['prompt'][:60]}\n"
        "This is a scaffold: review and extend before use.\n"
    )


def _py_header(blueprint: Dict[str, Any], kind: str) -> str:
    """Header formatted as Python comments for generated .py files."""
    return "\n".join("# " + line for line in _header(blueprint, kind).splitlines())


