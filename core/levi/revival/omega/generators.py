def _yaml_str(text: str) -> str:
    """Make free text safe for a double-quoted YAML frontmatter scalar."""
    return re.sub(r"\s+", " ", text or "").strip().replace('"', "'")


_AUTOMATION_RUNNER_SRC = '''"""Stdlib-only runner for the declarative WORKFLOW spec above.

A rite in three movements:

1. trigger — the knock that wakes the workflow. This scaffold defaults to
   ``manual``; write a schedule note or an event name here when this rite
   earns one.
2. steps   — small named actions, performed in order.
3. receipt — a sealed record of every run: printed as JSON and appended
   to the receipt journal.

Supported step actions: ``say`` (print a line), ``write`` (write text to a
file), ``stamp`` (append one line to the journal).

Nothing here touches the network or needs a third-party package.
"""


def _utcnow() -> str:
    return _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds")


def run_step(step, journal):
    """Perform one step; returns a small result record."""
    action = step.get("action", "say")
    if action == "say":
        print(step.get("says", step.get("name", "")))
    elif action == "write":
        path = Path(step["path"])
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(step.get("text", ""), encoding="utf-8")
        print(f"wrote {path}")
    elif action == "stamp":
        journal.parent.mkdir(parents=True, exist_ok=True)
        with journal.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps({"at": _utcnow(), "step": step.get("name")}) + "\\n")
        print(f"stamped {journal}")
    else:
        raise ValueError(f"unknown step action: {action!r}")
    return {"step": step.get("name"), "action": action, "ok": True}


def run_workflow(spec, dry_run=False):
    """Wake the workflow, perform its steps, seal the receipt."""
    journal = Path(spec.get("receipt", {}).get("journal", "receipts.jsonl"))
    started = _utcnow()
    if dry_run:
        print(f"[dry run] would perform {len(spec.get('steps', []))} steps")
        return {"workflow": spec.get("name"), "dry_run": True, "ok": True}
    results = [run_step(step, journal) for step in spec.get("steps", [])]
    receipt = {
        "workflow": spec.get("name"),
        "started": started,
        "finished": _utcnow(),
        "steps": results,
        "ok": True,
    }
    journal.parent.mkdir(parents=True, exist_ok=True)
    with journal.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(receipt) + "\\n")
    return receipt


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog=WORKFLOW.get("name", "workflow"))
    parser.add_argument("--dry-run", action="store_true",
                        help="rehearse without touching anything")
    args = parser.parse_args(argv)
    receipt = run_workflow(WORKFLOW, dry_run=args.dry_run)
    print(json.dumps(receipt, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


