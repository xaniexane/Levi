ORIGIN = "levi-revival-omega/alpha-x"


def _prov(blueprint: Dict[str, Any], kind: str) -> str:
    return (f"Generated by LEVI revival/omega ({ORIGIN}) | kind: {kind} "
            f"| app: {blueprint['name']}")


def _json(obj: Any, blueprint: Dict[str, Any], kind: str) -> str:
    """JSON with honest provenance baked in as the first key."""
    if isinstance(obj, dict):
        payload = {"_levi_provenance": _prov(blueprint, kind)}
        payload.update(obj)
    else:
        payload = {"_levi_provenance": _prov(blueprint, kind), "data": obj}
    return json.dumps(payload, indent=2) + "\n"


