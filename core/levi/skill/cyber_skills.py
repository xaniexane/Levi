"""LEVI cybersecurity skill library: data-driven registration.

Every playbook in ``playbooks/cyber/*.md`` carries a mandatory YAML
frontmatter block (parsed with stdlib only)::

    ---
    skill_id: cyber_<slug_with_underscores>
    name: Human Readable Title
    description: Single-sentence description.
    risk: info            # info | low | moderate | high | critical
    permissions: []
    requires_confirmation: false
    tags: [tag1, tag2]
    version: 1.0.0
    ---

``CYBER_SKILLS`` is built dynamically at import by scanning the directory:
no hand-maintained list, so later playbook batches register automatically
with zero merge conflicts. ``category`` is always ``"cybersecurity"`` and
the id scheme is locked to ``cyber_<slug_with_underscores>``.

Fast path: ``playbooks/cyber/cyber_index.jsonl.gz`` is a precomputed
manifest (one JSON object per line, gzip-compressed). When the manifest is
fresh — same entry count as the ``*.md`` glob and newer than every
playbook file — the import reads the manifest instead of parsing 100,000+
frontmatter blocks. Handlers stay lazy: a playbook file is read only when
its skill is invoked. Any manifest/file mismatch falls back to a full
directory scan (which also rebuilds the manifest), so correctness never
depends on the manifest.

All 100 batch-1 playbooks are original works authored for LEVI (defensive
blue-team lens: detection, analysis, hardening — never offensive
instructions). Topic coverage was inspired by the public listing at
``github.com/mukul975/Anthropic-Cybersecurity-Skills``; no content was
copied from that repository and its files were never read.

Batch-3 (``b3-*``) is 100,000 original combinatorial playbooks generated by
``cyber_gen/generate.py`` from 50 threat scenarios x 40 asset types x 10
environments x 5 maturity tiers. Every playbook is standalone defensive
blue-team material written from scratch for LEVI; no external repository
was contacted during generation.

Risk policy: read-only analysis playbooks are INFO/LOW. Anything that
acquires evidence images or touches live systems is MODERATE with
requires_confirmation=True.
"""

from __future__ import annotations

import gzip
import json
import re
import time
from pathlib import Path
from typing import Dict, List, Optional

from levi.skill.registry import Skill, SkillRisk

PLAYBOOK_DIR = Path(__file__).resolve().parent / "playbooks" / "cyber"

FRONTMATTER_KEYS = (
    "skill_id",
    "name",
    "description",
    "risk",
    "permissions",
    "requires_confirmation",
    "tags",
    "version",
)

_RISK_BY_NAME = {
    "info": SkillRisk.INFO,
    "low": SkillRisk.LOW,
    "moderate": SkillRisk.MODERATE,
    "high": SkillRisk.HIGH,
    "critical": SkillRisk.CRITICAL,
}
_RISK_NAME = {v: k for k, v in _RISK_BY_NAME.items()}

_ID_RE = re.compile(r"cyber_[a-z0-9_]+\Z")
_BOOL_RE = re.compile(r"\A(true|false)\Z")

MANIFEST_NAME = "cyber_index.jsonl.gz"
MANIFEST_VERSION = 1
# Only the head of each file is ever needed for frontmatter.
_FRONTMATTER_HEAD_BYTES = 8192


def _parse_frontmatter(path: Path) -> Optional[Dict[str, object]]:
    """Parse the mandatory frontmatter block using stdlib only.

    Supports ``key: value`` lines, ``[...]`` inline lists and
    true/false. Returns None when no well-formed block is present.
    Only the file head is read: frontmatter always opens the file.
    """
    try:
        with open(path, "r", encoding="utf-8") as fh:
            text = fh.read(_FRONTMATTER_HEAD_BYTES)
    except OSError:
        return None
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---", 4)
    if end == -1:
        return None
    meta: Dict[str, object] = {}
    for raw in text[4:end].splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip()
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            value = [  # type: ignore[assignment]
                item.strip().strip("'\"")
                for item in value[1:-1].split(",")
                if item.strip()
            ]
        elif _BOOL_RE.match(value.lower()):
            value = value.lower() == "true"  # type: ignore[assignment]
        else:
            value = value.strip("'\"")  # type: ignore[assignment]
        if key:
            meta[key] = value
    return meta


def _playbook_body(path: Path) -> str:
    """Playbook markdown with the frontmatter block stripped."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        return f"cyber skill playbook unavailable: {exc}"
    if text.startswith("---\n"):
        end = text.find("\n---", 4)
        if end != -1:
            return text[end + 4 :].lstrip("\n")
    return text


def _skill_from_meta(
    skill_id: str, meta: Dict[str, object], path: Path
) -> Optional[Skill]:
    """Build a Skill from parsed frontmatter; None if it is not usable.

    Files without a valid frontmatter block are skipped (never crash the
    import: a second writer batch lands files in this directory while it
    is still being written). The test suite enforces the invariant that
    every file carries valid frontmatter.
    """
    if any(k not in meta for k in FRONTMATTER_KEYS):
        return None
    expected_id = "cyber_" + path.stem.replace("-", "_")
    if not _ID_RE.match(skill_id) or skill_id != expected_id:
        return None
    risk = _RISK_BY_NAME.get(str(meta["risk"]).lower())
    if risk is None:
        return None
    permissions = meta["permissions"]
    tags = meta["tags"]
    requires_confirmation = meta["requires_confirmation"]
    if (
        not isinstance(permissions, list)
        or not isinstance(tags, list)
        or not isinstance(requires_confirmation, bool)
    ):
        return None

    def _handler(_args: dict, _path: Path = path) -> str:
        # Lazy: the playbook file is read only when the skill is invoked.
        # Return the raw playbook file: batch-2 playbooks carry their title
        # only in frontmatter, so the block is kept, not stripped.
        try:
            return _path.read_text(encoding="utf-8")
        except OSError as exc:
            return f"cyber skill playbook unavailable: {exc}"

    return Skill(
        id=skill_id,
        name=str(meta["name"]),
        description=str(meta["description"]),
        category="cybersecurity",
        version=str(meta["version"]),
        risk_level=risk,
        permissions=[str(p) for p in permissions],
        requires_confirmation=requires_confirmation,
        tags=[str(t) for t in tags],
        handler=_handler,
    )


def _skill_from_file(path: Path) -> Optional[Skill]:
    """Build a Skill from one playbook file; None if it is not usable."""
    meta = _parse_frontmatter(path)
    if meta is None:
        return None
    skill_id = str(meta.get("skill_id", ""))
    return _skill_from_meta(skill_id, meta, path)


def _manifest_path() -> Path:
    return PLAYBOOK_DIR / MANIFEST_NAME


def _manifest_usable() -> bool:
    """True when the manifest exists, its entry count matches the *.md
    files on disk, and it is newer than every playbook file. Any doubt ->
    full scan (correctness first).

    Single os.scandir pass (count + mtimes together, cached stats):
    ~100k entries check in a couple of seconds.
    """
    import os

    mp = _manifest_path()
    if not mp.is_file():
        return False
    try:
        with gzip.open(mp, "rt", encoding="utf-8") as fh:
            header = json.loads(fh.readline())
    except Exception:
        return False
    if header.get("manifest") != MANIFEST_VERSION:
        return False
    try:
        mtime = mp.stat().st_mtime
        seen = 0
        with os.scandir(PLAYBOOK_DIR) as it:
            for entry in it:
                if not entry.name.endswith(".md"):
                    continue
                seen += 1
                if entry.stat().st_mtime > mtime:
                    return False
        if seen != header.get("count"):
            return False
    except OSError:
        return False
    return True


def _skills_from_manifest() -> List[Skill]:
    """Build Skills from the manifest. Raises on any inconsistency so the
    caller falls back to a full directory scan."""
    mp = _manifest_path()
    skills: List[Skill] = []
    with gzip.open(mp, "rt", encoding="utf-8") as fh:
        header = json.loads(fh.readline())
        count = int(header["count"])
        for line in fh:
            line = line.strip()
            if not line:
                continue
            entry = json.loads(line)
            skill_id = entry["skill_id"]
            path = PLAYBOOK_DIR / (
                skill_id[len("cyber_") :].replace("_", "-") + ".md"
            )
            # No per-entry existence stat: _manifest_usable() verified the
            # file count and freshness milliseconds ago, and the count check
            # below catches any mid-read inconsistency (falls back to scan).
            meta = {
                "skill_id": skill_id,
                "name": entry["name"],
                "description": entry["description"],
                "risk": entry["risk"],
                "permissions": entry["permissions"],
                "requires_confirmation": entry["requires_confirmation"],
                "tags": entry["tags"],
                "version": entry["version"],
            }
            skill = _skill_from_meta(skill_id, meta, path)
            if skill is None:
                raise ValueError(f"manifest entry invalid: {skill_id}")
            skills.append(skill)
    if len(skills) != count:
        raise ValueError(f"manifest count {count} != entries read {len(skills)}")
    return skills


def _write_manifest(skills: List[Skill]) -> None:
    """Rebuild the manifest from a freshly scanned skill list (best effort)."""
    mp = _manifest_path()
    tmp = mp.with_name(mp.name + ".tmp")
    with gzip.open(tmp, "wt", encoding="utf-8") as fh:
        fh.write(
            json.dumps(
                {
                    "manifest": MANIFEST_VERSION,
                    "count": len(skills),
                    "built_at": time.time(),
                }
            )
            + "\n"
        )
        for s in skills:
            fh.write(
                json.dumps(
                    {
                        "skill_id": s.id,
                        "name": s.name,
                        "description": s.description,
                        "risk": _RISK_NAME[s.risk_level],
                        "permissions": s.permissions,
                        "requires_confirmation": s.requires_confirmation,
                        "tags": s.tags,
                        "version": s.version,
                    }
                )
                + "\n"
            )
    tmp.replace(mp)


def _load_cyber_skills() -> List[Skill]:
    """Scan the playbook directory and build every Skill dynamically.

    Prefers the manifest when it is fresh (single scandir pass for the
    count + freshness check — no 100k glob on the happy path); falls back
    to a full scan (which rebuilds the manifest) on any mismatch.
    """
    skills: List[Skill] = []
    if not PLAYBOOK_DIR.is_dir():
        return skills
    if _manifest_usable():
        try:
            return _skills_from_manifest()
        except Exception:
            pass  # fall through to the full scan below
    for path in sorted(PLAYBOOK_DIR.glob("*.md")):
        skill = _skill_from_file(path)
        if skill is not None:
            skills.append(skill)
    try:
        _write_manifest(skills)
    except Exception:
        pass  # manifest is an optimization, never a requirement
    return skills


# The full registration list, built dynamically at import.
# SkillRegistry consumes this (import + extend).
CYBER_SKILLS: List[Skill] = _load_cyber_skills()
