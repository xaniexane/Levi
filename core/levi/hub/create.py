"""hub.create: the Creation Console — PL-03's product surface.

One command turns a prompt into a receipted build directory:

    levi create "a simple todo list web page" --dest ~/builds/todo
    levi create "prompt" --dest DIR --approve      # materialize (writes)
    levi create --list                             # past creations (read-only)
    levi create --verify <id>                      # re-check hashes (read-only)

The engine is the hardened forge pipeline (``levi.revival.omega.pipeline``:
Echo -> Alpha -> preview -> permission -> materialize -> nexus -> receipt).
This module is the product layer on top of it:

- **HONEST.md** — every materialized build carries a scaffold disclaimer
  (PL-03 build route: generators emit genuine working scaffolds, never
  claim production-readiness for a fresh build).
- **Creation ledger** — append-only JSONL at ``~/.levi/creation/ledger.jsonl``.
  Every run is recorded: ok, refused, or errored, with per-file sha256
  linked to the pipeline receipt. No edit/delete API exists.
- **verify** — re-checks ledgered sha256 hashes against disk, catching
  tamper-after-write.

LAWS (invariants; each has a proof test in test_hub_create.py):

1. No artifact files are written without explicit approval. With
   ``approve=False`` the run ends at the permission stage and the only
   filesystem effect is the (possibly created, empty) dest directory.
2. Dest containment: every path recorded in the ledger resolves inside
   dest. The pipeline's materializer enforces this; the console re-asserts
   it before ledgering.
3. Honest labeling: every ok materialization contains HONEST.md with the
   scaffold disclaimer, prompt hash, and build timestamp.
4. Receipt linkage: ledger entries carry the pipeline's stage outcomes
   and per-file sha256; ``verify`` recomputes hashes from disk.
5. Read-only commands: ``list_creations`` and ``verify`` never write to
   dest or to the ledger.
6. Append-only ledger: entries are only ever appended; the module exposes
   no mutation or deletion.

Stdlib only. Local-first. Single-user (multi-user/hosted is a deferred
founder decision per docs/PRODUCT_LINES.md). No money code anywhere.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from levi.revival.omega import pipeline as _forge

CREATION_ROOT = Path.home() / ".levi" / "creation"
LEDGER_PATH = CREATION_ROOT / "ledger.jsonl"
HONEST_NAME = "HONEST.md"

HONEST_TEMPLATE = """# HONEST.md — scaffold disclaimer

This directory was generated by **LEVI Creation (PL-03)** — the Alpha
creation lab: a prompt went in, Echo drafted the blueprint, Alpha compiled
it through template generators.

**What this is:** a genuine working scaffold, assembled from templates.
**What this is not:** a production application. It has not been reviewed,
hardened, or tested for real-world use.

- Prompt (sha256): {prompt_sha}
- Product types: {product_types}
- Built at: {built_at}
- Files: {file_count}
- Creation id: {creation_id}

Verify everything before use. Never claim production-readiness for a
fresh build.
"""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _ensure_root() -> Path:
    CREATION_ROOT.mkdir(parents=True, exist_ok=True)
    return CREATION_ROOT


def _append_ledger(entry: Dict[str, Any]) -> None:
    """Append one entry. There is deliberately no edit/delete path."""
    _ensure_root()
    line = json.dumps(entry, sort_keys=True)
    # O_APPEND: concurrent appends cannot interleave or clobber.
    fd = os.open(LEDGER_PATH, os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
    try:
        os.write(fd, (line + "\n").encode("utf-8"))
    finally:
        os.close(fd)


def _read_ledger() -> List[Dict[str, Any]]:
    if not LEDGER_PATH.exists():
        return []
    entries = []
    with open(LEDGER_PATH, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                entries.append(json.loads(line))
    return entries


def _resolve_inside(dest: Path, rel: str) -> Path:
    """Resolve a ledgered relative path; refuse anything escaping dest."""
    target = (dest / rel).resolve()
    dest_r = dest.resolve()
    if target != dest_r and dest_r not in target.parents:
        raise ValueError(f"ledgered path escapes dest: {rel!r}")
    return target


def _honest_text(*, prompt_sha: str, product_types: Any,
                 built_at: str, file_count: int, creation_id: str) -> str:
    types = ", ".join(product_types) if product_types else "undetected"
    return HONEST_TEMPLATE.format(
        prompt_sha=prompt_sha,
        product_types=types,
        built_at=built_at,
        file_count=file_count,
        creation_id=creation_id,
    )


def create(
    prompt: str,
    dest: str,
    *,
    approve: bool = False,
    overwrite: bool = False,
    generator: Optional[str] = None,
) -> Dict[str, Any]:
    """Run one creation. Returns a summary dict; always ledgered.

    approve=False (default): design + preview only, zero artifact files.
    approve=True: materialize to dest, write HONEST.md, ledger with hashes.
    """
    if not prompt or not str(prompt).strip():
        raise ValueError("prompt is required — say what to build")
    if not dest or not str(dest).strip():
        raise ValueError("dest is required — give me a real directory")
    prompt = str(prompt).strip()
    dest_p = Path(dest).expanduser()
    creation_id = uuid.uuid4().hex[:12]
    prompt_sha = _sha256_text(prompt)
    built_at = _now()

    # Law 1: the empty dest dir may be created for preview; no artifacts
    # are written unless the pipeline's permission stage is satisfied.
    dest_p.mkdir(parents=True, exist_ok=True)

    receipt = _forge.run_pipeline(
        prompt,
        dest=str(dest_p),
        approve=approve,
        overwrite=overwrite,
        generator=generator,
    )

    stages = [
        {"stage": s.get("stage"), "ok": bool(s.get("ok")),
         "did": s.get("did"), "did_not": s.get("did_not")}
        for s in receipt.get("stages", [])
    ]
    materialize_data: Dict[str, Any] = {}
    for s in receipt.get("stages", []):
        if s.get("stage") == "materialize":
            materialize_data = s.get("data", {}) or {}
            break
    written = materialize_data.get("written", []) or []

    # Law 2: re-assert dest containment before anything is ledgered.
    files: List[Dict[str, Any]] = []
    for w in written:
        rel = w.get("path", "")
        _resolve_inside(dest_p, rel)  # raises on escape
        files.append({
            "path": rel,
            "bytes": w.get("bytes"),
            "sha256": w.get("sha256"),
        })

    honest_ok = False
    if receipt.get("ok") and files:
        # Law 3: honest labeling on every successful materialization.
        honest_path = dest_p / HONEST_NAME
        honest_path.write_text(
            _honest_text(
                prompt_sha=prompt_sha,
                product_types=(receipt.get("blueprint") or {}).get("product_types"),
                built_at=built_at,
                file_count=len(files),
                creation_id=creation_id,
            ),
            encoding="utf-8",
        )
        files.append({
            "path": HONEST_NAME,
            "bytes": honest_path.stat().st_size,
            "sha256": _sha256_file(honest_path),
        })
        honest_ok = True

    entry = {
        "id": creation_id,
        "ts": built_at,
        "prompt": prompt,
        "prompt_sha256": prompt_sha,
        "dest": str(dest_p),
        "product_types": (receipt.get("blueprint") or {}).get("product_types"),
        "ok": bool(receipt.get("ok")),
        "honest_label": honest_ok,
        "stages": stages,
        "files": files,
        "limits": receipt.get("limits"),
    }
    # Law 6: the ledger only grows.
    _append_ledger(entry)

    return {
        "id": creation_id,
        "ok": entry["ok"],
        "dest": str(dest_p),
        "files": [f["path"] for f in files],
        "honest_label": honest_ok,
        "product_types": entry["product_types"],
        "approved": approve,
        "note": (
            "materialized with scaffold disclaimer"
            if entry["ok"]
            else "nothing materialized — see stages for the refusing stage"
        ),
    }


def list_creations(limit: int = 20) -> List[Dict[str, Any]]:
    """Past creations, newest last. Read-only (Law 5)."""
    entries = _read_ledger()
    return entries[-limit:] if limit > 0 else entries


def get_creation(creation_id: str) -> Dict[str, Any]:
    """Fetch one ledger entry by id. Read-only."""
    for entry in _read_ledger():
        if entry.get("id") == creation_id:
            return entry
    raise ValueError(f"unknown creation id: {creation_id!r}")


def verify(creation_id: str) -> Dict[str, Any]:
    """Re-check a creation's ledgered sha256 hashes against disk.

    Read-only (Law 5). Catches tamper-after-write, accidental edits,
    and missing files.
    """
    entry = get_creation(creation_id)
    dest_p = Path(entry["dest"])
    mismatches: List[str] = []
    missing: List[str] = []
    checked = 0
    for f in entry.get("files", []):
        rel = f["path"]
        target = _resolve_inside(dest_p, rel)
        if not target.exists():
            missing.append(rel)
            continue
        checked += 1
        if _sha256_file(target) != f.get("sha256"):
            mismatches.append(rel)
    ok = not mismatches and not missing
    return {
        "id": creation_id,
        "ok": ok,
        "checked": checked,
        "mismatches": mismatches,
        "missing": missing,
        "created_at": entry.get("ts"),
    }


def main(argv: Optional[List[str]] = None) -> int:
    """``levi create`` CLI."""
    ap = argparse.ArgumentParser(
        prog="levi create",
        description="PL-03 Creation Console: prompt -> receipted build directory.",
    )
    ap.add_argument("prompt", nargs="?",
                    help="what to build (omit with --list / --verify)")
    ap.add_argument("--dest",
                    help="build directory (created if missing)")
    ap.add_argument("--approve", action="store_true",
                    help="explicit approval: materialize files to --dest")
    ap.add_argument("--overwrite", action="store_true",
                    help="allow writing into a non-empty --dest")
    ap.add_argument("--generator",
                    help="force one generator (default: blueprint decides)")
    ap.add_argument("--list", action="store_true",
                    help="show past creations (read-only)")
    ap.add_argument("--limit", type=int, default=20,
                    help="max entries for --list")
    ap.add_argument("--verify",
                    help="re-check creation ID's files against disk (read-only)")
    args = ap.parse_args(argv)

    if args.list:
        for e in list_creations(limit=args.limit):
            status = "ok" if e.get("ok") else "refused"
            print(f"{e['id']}  {e['ts']}  [{status}]  {e['dest']}")
            print(f"    prompt: {e['prompt'][:90]}")
        return 0
    if args.verify:
        v = verify(args.verify)
        print(json.dumps(v, indent=2))
        return 0 if v["ok"] else 1
    if not args.prompt:
        ap.error("prompt is required (or use --list / --verify)")
    if not args.dest:
        ap.error("--dest is required")
    summary = create(
        args.prompt,
        args.dest,
        approve=args.approve,
        overwrite=args.overwrite,
        generator=args.generator,
    )
    print(json.dumps(summary, indent=2))
    if not summary["ok"]:
        print("Refused — no files materialized. "
              "Re-run with --approve to materialize.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
